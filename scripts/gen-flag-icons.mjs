/**
 * Regenerates src/config/flag-icons.ts with only the flag icons referenced by
 * LANGUAGE_LIST in src/config/app.config.ts, extracted from @iconify-json/flagpack.
 *
 * Run: node scripts/gen-flag-icons.mjs
 *
 * When adding a language, add its `flag` (e.g. "flagpack:fr") to LANGUAGE_LIST,
 * then re-run this script so the new flag is bundled offline.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { icons } = require('@iconify-json/flagpack')

// Pull the flag icon names ("flagpack:<name>") out of app.config.ts,
// ignoring commented-out lines (e.g. the "add more languages" example).
const config = readFileSync('src/config/app.config.ts', 'utf8')
    .split('\n')
    .filter((line) => !line.trim().startsWith('//'))
    .join('\n')
const needed = [
    ...new Set([...config.matchAll(/flagpack:([a-z0-9-]+)/g)].map((m) => m[1])),
]

if (needed.length === 0) {
    console.error('No flagpack:* icons found in src/config/app.config.ts')
    process.exit(1)
}

const subset = {
    prefix: icons.prefix,
    width: icons.width,
    height: icons.height,
    icons: {},
}

for (const name of needed) {
    if (!icons.icons[name]) {
        console.error(`Missing flag icon in @iconify-json/flagpack: ${name}`)
        process.exit(1)
    }
    subset.icons[name] = icons.icons[name]
}

const header = `import type { IconifyJSON } from '@iconify/react'

/**
 * Offline flag icons for the languages in app.config.ts LANGUAGE_LIST.
 * Only the flags actually in use are bundled (not the full flagpack set).
 *
 * Generated by scripts/gen-flag-icons.mjs — do not edit by hand.
 */
export const FLAG_ICONS: IconifyJSON = `

writeFileSync(
    'src/config/flag-icons.ts',
    header + JSON.stringify(subset, null, 4) + '\n'
)
console.log(
    `Wrote src/config/flag-icons.ts with icons: ${needed.join(', ')}`
)
